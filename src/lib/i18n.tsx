const STORAGE_KEY = "nelson-fms-lang";

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    try {
      const saved = window.localStorage.getItem(STORAGE_KEY) as Lang | null;
      if (saved && (saved === "en" || saved === "hi" || saved === "mr")) setLangState(saved);
    } catch {}
  }, []);
  const setLang = (l: Lang) => {
    setLangState(l);
    try { window.localStorage.setItem(STORAGE_KEY, l); } catch {}
  };
  const t = (key: string) => DICT[lang][key] ?? DICT.en[key] ?? key;
  return <I18nCtx.Provider value={{ lang, setLang, t }}>{children}</I18nCtx.Provider>;
}

export function useI18n() {
  const v = useContext(I18nCtx);
  if (!v) return { lang: "en" as Lang, setLang: () => {}, t: (k: string) => DICT.en[k] ?? k };
  return v;
}

export function LanguageSwitcher({ className = "" }: { className?: string }) {
  const { lang, setLang } = useI18n();
  return (
    <select
      value={lang}
      onChange={(e) => setLang(e.target.value as Lang)}
      className={`text-xs rounded-md border border-white/20 bg-white/10 text-current px-2 py-1 outline-none ${className}`}
      aria-label="Language"
    >
      <option value="en" className="text-foreground">English</option>
      <option value="hi" className="text-foreground">हिन्दी</option>
      <option value="mr" className="text-foreground">मराठी</option>
    </select>
  );
}
